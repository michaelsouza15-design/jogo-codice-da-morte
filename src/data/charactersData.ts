// Helper para buscar qualquer um dos 42 personagens por id, número ou nome
export const getCharacterById = (idOrAlias?: string): Character => {
  if (!idOrAlias) return CHARACTERS[0];
  const query = idOrAlias.toLowerCase().trim();

  // 1. Direct match by id
  const direct = CHARACTERS.find((c) => c.id.toLowerCase() === query);
  if (direct) return direct;

  // 2. Direct match by number (e.g. "1", "01", "42")
  const asNum = parseInt(query, 10);
  if (!isNaN(asNum)) {
    const byNum = CHARACTERS.find((c) => c.number === asNum);
    if (byNum) return byNum;
  }

  // 3. Match by name or nome
  const byName = CHARACTERS.find(
    (c) => c.name.toLowerCase() === query || (c.nome && c.nome.toLowerCase() === query)
  );
  if (byName) return byName;

  // 4. Match by aliases
  const byAlias = CHARACTERS.find((c) => c.aliases?.some((a) => a.toLowerCase() === query));
  if (byAlias) return byAlias;

  // 5. Partial match
  const byPartial = CHARACTERS.find(
    (c) =>
      c.id.toLowerCase().includes(query) ||
      query.includes(c.id.toLowerCase()) ||
      c.name.toLowerCase().includes(query) ||
      (c.aliases && c.aliases.some((a) => query.includes(a.toLowerCase()) || a.toLowerCase().includes(query)))
  );
  if (byPartial) return byPartial;

  return CHARACTERS[0];
};
